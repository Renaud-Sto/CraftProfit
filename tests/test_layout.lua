local H = ...

local function load()
    return H.newNS("Util", "UI/Layout").Layout
end

H.test("panelHeight adds the header, the body padding and the rows", function()
    local Layout = load()
    H.eq(Layout.panelHeight(3, 18), 22 + 8 + 54)
    H.eq(Layout.panelHeight(0, 18), 30)
    H.eq(Layout.panelHeight(nil, 18), 30)
    H.eq(Layout.panelHeight(-4, 18), 30)
    H.eq(Layout.panelHeight(2, 18, 10), 22 + 8 + 36 + 10)
    H.eq(Layout.panelHeight(2.9, 10), 22 + 8 + 20)
end)

H.test("stack places panels one under the other with a gap and reports the total", function()
    local Layout = load()
    local offsets, total = Layout.stack({ 30, 20 }, 8, 10)
    H.eq(offsets, { -10, -48 })
    H.eq(total, 58)
    offsets, total = Layout.stack({ 50 }, 8)
    H.eq(offsets, { 0 })
    H.eq(total, 50)
    offsets, total = Layout.stack({}, 8)
    H.eq(offsets, {})
    H.eq(total, 0)
end)

H.test("fitSize picks the largest size that fits, the smallest when none does", function()
    local Layout = load()
    local sizes = { 19, 17, 15, 13 }
    H.eq(Layout.fitSize(100, 19, 120, sizes), 19)
    H.eq(Layout.fitSize(150, 19, 120, sizes), 15)
    H.eq(Layout.fitSize(1000, 19, 120, sizes), 13)
    H.eq(Layout.fitSize(nil, 19, 120, sizes), 19)
    H.eq(Layout.fitSize("x", 19, 120, sizes), 19)
    H.eq(Layout.fitSize(150, 0, 120, sizes), 19)
end)

H.test("scrollThumb sizes and places the thumb, nil when the list fits", function()
    local Layout = load()
    local h, top = Layout.scrollThumb(12, 6, 0, 100)
    H.eq({ h, top }, { 50, 0 })
    h, top = Layout.scrollThumb(12, 6, 6, 100)
    H.eq({ h, top }, { 50, 50 })
    h, top = Layout.scrollThumb(12, 6, 3, 100)
    H.eq({ h, top }, { 50, 25 })
    h = Layout.scrollThumb(1000, 6, 0, 100)
    H.eq(h, Layout.SCROLL_MIN_THUMB)
    H.eq(Layout.scrollThumb(6, 6, 0, 100), nil)
    H.eq(Layout.scrollThumb(3, 6, 0, 100), nil)
    H.eq(Layout.scrollThumb(12, 0, 0, 100), nil)
    H.eq(Layout.scrollThumb(12, 6, 0, 0), nil)
    H.eq(Layout.scrollThumb(nil, 6, 0, 100), nil)
    top = select(2, Layout.scrollThumb(12, 6, 99, 100))
    H.eq(top, 50)
    top = select(2, Layout.scrollThumb(12, 6, -4, 100))
    H.eq(top, 0)
end)

H.test("scrollOffsetAt maps a pointer position to a row offset and clamps it", function()
    local Layout = load()
    H.eq(Layout.scrollOffsetAt(12, 6, 100, 0), 0)
    H.eq(Layout.scrollOffsetAt(12, 6, 100, 100), 6)
    H.eq(Layout.scrollOffsetAt(12, 6, 100, 50), 3)
    H.eq(Layout.scrollOffsetAt(12, 6, 100, -30), 0)
    H.eq(Layout.scrollOffsetAt(12, 6, 100, 400), 6)
    H.eq(Layout.scrollOffsetAt(5, 6, 100, 50), 0)
    H.eq(Layout.scrollOffsetAt(nil, 6, 100, 50), 0)
end)

H.test("scrollGrab keeps the place of a thumb grabbed anywhere and centres a pointer off the thumb", function()
    local Layout = load()
    -- 12 rows, 6 visible, track 100: the thumb is 50 high; at offset 0 it covers y 0..50
    H.eq(Layout.scrollGrab(12, 6, 0, 100, 10), 10)
    H.eq(Layout.scrollGrab(12, 6, 0, 100, 50), 50)
    H.eq(Layout.scrollGrab(12, 6, 0, 100, 80), 25)
    -- at offset 6 it covers y 50..100
    H.eq(Layout.scrollGrab(12, 6, 6, 100, 60), 10)
    H.eq(Layout.scrollGrab(12, 6, 6, 100, 20), 25)
    H.eq(Layout.scrollGrab(6, 6, 0, 100, 10), nil)
    H.eq(Layout.scrollGrab(nil, 6, 0, 100, 10), nil)
end)

H.test("rightmost picks the shown entry with the largest right edge", function()
    local Layout = load()
    H.eq(Layout.rightmost({}), nil)
    H.eq(Layout.rightmost({ { shown = false, right = 900 } }), nil)
    H.eq(Layout.rightmost({ { shown = true, right = 300 }, { shown = true, right = 700 }, { shown = false, right = 900 } }), 2)
    H.eq(Layout.rightmost({ { shown = true, right = 700 }, { shown = true, right = 700 } }), 1)
    -- An edge that cannot be measured never wins: nothing to place beside.
    H.eq(Layout.rightmost({ { shown = true, right = nil }, { shown = true, right = 0 / 0 } }), nil)
    H.eq(Layout.rightmost({ { shown = true, right = math.huge }, { shown = true, right = "9" }, { shown = true, right = 5 } }), 3)
    H.eq(Layout.rightmost({ { shown = 1, right = 5 } }), nil)
end)

H.test("textWidth estimates a label from its letters, accents counting once", function()
    local Layout = load()
    H.eq(Layout.textWidth("abc", 7), 21)
    H.eq(Layout.textWidth("Montée de métier", 7), 16 * 7)
    H.eq(Layout.textWidth("", 7), 0)
    H.eq(Layout.textWidth(nil, 7), 0)
end)

H.test("wrapLines estimates the lines of a text wrapped at word boundaries", function()
    local Layout = load()
    H.eq(Layout.wrapLines(nil, 6, 100), 0)
    H.eq(Layout.wrapLines("", 6, 100), 0)
    -- "aaaa bbbb" is 9 letters = 54 px.
    H.eq(Layout.wrapLines("aaaa bbbb", 6, 54), 1)
    H.eq(Layout.wrapLines("aaaa bbbb", 6, 53), 2)
    H.eq(Layout.wrapLines("aaaa bbbb cccc", 6, 60), 2)
    -- A word wider than the line takes a line of its own.
    H.eq(Layout.wrapLines("a bbbbbbbbbbbb c", 6, 30), 3)
    -- Accented letters count once.
    H.eq(Layout.wrapLines("éé éé", 6, 30), 1)
end)
